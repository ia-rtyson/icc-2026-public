def listConfigs():
	"""Every saved dashboard, newest-touched first, without its widgets payload.

	Returns a list of dicts: id, name, isDemo, widgetCount, updated. Feeds the
	Manage popup's table directly.
	"""
	_ensureTable()
	rs = system.db.runNamedQuery(PROJECT, NQ + 'SelectConfigList', {})
	return [_row(rs, i) for i in range(rs.getRowCount())]


def getConfig(ident):
	"""One saved dashboard including its widgets list, or None.

	Args:
		ident: row id (int) or name (string, case-insensitive).
	"""
	_ensureTable()
	if isinstance(ident, basestring):
		rs = system.db.runNamedQuery(PROJECT, NQ + 'SelectConfigByName', {'name': ident})
	else:
		rs = system.db.runNamedQuery(PROJECT, NQ + 'SelectConfigById', {'id': int(ident)})
	if rs.getRowCount() == 0:
		return None
	return {
		'id': rs.getValueAt(0, 'id'),
		'name': rs.getValueAt(0, 'name'),
		'isDemo': bool(rs.getValueAt(0, 'is_demo')),
		'widgets': system.util.jsonDecode(rs.getValueAt(0, 'widgets_text')),
	}


def exists(name):
	"""True if a dashboard is already saved under this name (case-insensitive)."""
	_ensureTable()
	rs = system.db.runNamedQuery(PROJECT, NQ + 'SelectConfigByName', {'name': name or ''})
	return rs.getRowCount() > 0


