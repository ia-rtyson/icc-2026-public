def purgeStale():
	"""Delete non-demo dashboards last touched before today.

	Called every 15 minutes by the DashboardConfigPurge gateway timer, so the
	sweep happens shortly after midnight without a cron facility -- gateway
	event scripts do not have one.

	Keyed on ``updated_at`` rather than ``created_at`` deliberately: a dashboard
	saved late last night and still being edited this morning carries today's
	timestamp and survives, which is the forgiving reading of "wipe them at the
	end of the day". Rows with is_demo = true are never touched.

	Gated by the ``[default]Exchange/Demo/Control/Timers/DashboardConfigPurgeEnabled``
	switch, which fails closed -- see :mod:`exchange.demo.control`. Returns 0 without
	touching the table when the switch is off or unreadable.
	"""
	if not exchange.demo.control.timerEnabled('DashboardConfigPurge'):
		return 0
	_ensureTable()
	rows = system.db.runNamedQuery(PROJECT, NQ + 'DeleteStaleConfigs', {})
	if rows:
		log.infof('Nightly purge removed %d non-demo dashboard(s)', rows)
	return rows


def status():
	"""Pre-stage health check: what is saved, and what tonight's purge will take."""
	_ensureTable()
	rs = system.db.runNamedQuery(PROJECT, NQ + 'SelectConfigStatus', {})
	return {
		'total': rs.getValueAt(0, 'total'),
		'demo': rs.getValueAt(0, 'demo'),
		'purgeableNow': rs.getValueAt(0, 'stale'),
	}
