"""CRUD for saved Dashboard Agent layouts.

The Dashboard Agent builds a layout into the ``ia.display.dashboard``
component's ``props.widgets`` and that is session state -- reload the page and
it is gone. This module is what makes a layout outlive the session: save the
widgets array under a name, list what has been saved, load one back into the
component, edit it, delete it.

What is stored is **only** ``props.widgets``. ``props.availableWidgets`` -- the
catalog the agent picks from -- is generated by
``scripts/gen_dashboard_widgets.py`` into view.json and is deliberately not
persisted, so regenerating the catalog reaches every saved dashboard rather than
leaving each row pinned to the catalog that existed when it was saved.

Housekeeping: this is a demo gateway, so anything saved here is assumed
disposable unless it is explicitly flagged. ``purgeStale`` (driven by the
``DashboardConfigPurge`` gateway timer) deletes every row that is not
``is_demo`` once the day it was last touched has passed. Flagging a row demo is
the only way to keep it, and it is the only column the Manage popup can edit.

Schema: sql/006_dashboard_configs.sql. ``_ensureTable`` mirrors it as an
idempotent fallback, the same arrangement as exchange.alarmFlood.data.setupTables().
"""

import os

log = system.util.getLogger('exchange.dashboard.Configs')

DB = 'postgres'
TABLE = 'ex_icc_dashboard_config'
PROJECT = 'icc-2026'

# Named-query folder. Every read and write goes through a query in it; only
# the DDL fallback in _ensureTable is scripted, mirroring the migration.
NQ = 'Exchange/Dashboard/'

# Longest name the Save popup will accept. Not a schema limit (the column is
# TEXT) -- it is what keeps the Manage table readable.
MAX_NAME = 80

# The dashboard the page opens on (the Dashboard view root's onStartup loads it,
# see exchange.dashboard.ui.applyDefault). Seeded by sql/014_dashboard_default.sql
# and protected below: it cannot be deleted or lose its demo flag from the UI,
# because either would leave the page opening blank again. Re-saving a layout
# under this name from the page is how the default is changed.
DEFAULT_NAME = 'Line Overview'


# ---------------------------------------------------------------------------
# Plumbing
# ---------------------------------------------------------------------------

# Set once the DDL below has succeeded in this script lifetime. Every public
# function calls _ensureTable(), including ones Perspective polls, so without
# this each poll issued three DDL statements.
_tableReady = False


def _ensureTable():
	"""Create the table if it is missing. Mirrors sql/006_dashboard_configs.sql.

	The migration is the source of truth and runs on every `docker compose up`;
	this exists so a gateway pointed at a database that never saw the migration
	still works instead of failing on the first save. Runs its DDL at most once
	per script lifetime.
	"""
	global _tableReady
	if _tableReady:
		return
	system.db.runUpdateQuery(
		"CREATE TABLE IF NOT EXISTS %s ("
		"id SERIAL NOT NULL,"
		"name TEXT NOT NULL,"
		"widgets_json JSONB NOT NULL,"
		"is_demo BOOLEAN NOT NULL DEFAULT FALSE,"
		"created_at TIMESTAMPTZ NOT NULL DEFAULT now(),"
		"updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),"
		"CONSTRAINT ex_icc_dashboard_config_pkey PRIMARY KEY (id))" % TABLE, DB)
	system.db.runUpdateQuery(
		"CREATE UNIQUE INDEX IF NOT EXISTS ex_icc_dashboard_config_name_key "
		"ON %s (lower(name))" % TABLE, DB)
	system.db.runUpdateQuery(
		"CREATE INDEX IF NOT EXISTS ex_icc_dashboard_config_purge_idx "
		"ON %s (is_demo, updated_at)" % TABLE, DB)
	_tableReady = True


def _toPlain(obj, depth=0):
	"""Convert a Perspective property object into plain dicts/lists/primitives.

	``props.widgets`` is a PropertyTreeScriptWrapper, not a list -- it cannot be
	handed to a prepared statement, and jsonEncode on it is not reliable across
	shapes. Depth-capped and stringifies anything unrecognised, so serialisation
	always terminates.

	Mappings are tested BEFORE sequences, and that order is the whole point. A
	Perspective object wrapper (each widget in the array) has no ``keySet``,
	but it does have ``__iter__`` -- which yields its keys. Testing for
	iterables first therefore turned every widget into a list of its own key
	names, and that is what both saved dashboards held until 2026-10-01. Anything
	with ``keys()`` and ``get()`` is a mapping here, whatever its class.
	"""
	if depth > 20:
		return unicode(obj)
	if obj is None or isinstance(obj, (bool, int, long, float)):
		return obj
	if isinstance(obj, basestring):
		return obj
	# A QualifiedValue (what a bound property can hand back) -- keep the value
	if hasattr(obj, 'getQuality') and hasattr(obj, 'getValue'):
		return _toPlain(obj.getValue(), depth + 1)
	if isinstance(obj, dict):
		return dict((unicode(k), _toPlain(v, depth + 1)) for k, v in obj.items())
	# Perspective ObjectWrapper (keys/get/items, but no __getitem__ in dir()),
	# Java Map, or any other dict-like wrapper
	if hasattr(obj, 'keys') and hasattr(obj, 'get'):
		try:
			return dict((unicode(k), _toPlain(obj.get(k), depth + 1)) for k in obj.keys())
		except:
			pass
	if hasattr(obj, 'keySet') and hasattr(obj, 'get'):
		try:
			return dict((unicode(k), _toPlain(obj.get(k), depth + 1))
						for k in obj.keySet())
		except:
			return unicode(obj)
	if isinstance(obj, (list, tuple)):
		return [_toPlain(x, depth + 1) for x in obj]
	if hasattr(obj, 'iterator') or hasattr(obj, '__iter__'):
		try:
			return [_toPlain(x, depth + 1) for x in obj]
		except:
			return unicode(obj)
	return unicode(obj)


def catalog():
	"""The dashboard's ``availableWidgets`` catalog, read from view.json on disk.

	The agent's `getAvailableWidgets` tool used to read it off the component
	with ``self.getSibling("Dashboard")``. That stopped being possible when the
	chat moved into a dock: the dashboard component is on the page and the chat
	is in a different view, and Perspective has no cross-view property read.

	Reading the resource file instead makes the tool independent of where either
	component sits, and the file is the source of truth anyway --
	``scripts/gen_dashboard_widgets.py`` generates the catalog into it.
	"""
	# Gateway-only class, so imported here rather than at module top: a
	# module-level import would stop this whole library loading in any
	# Designer or client scope that touches it
	from com.inductiveautomation.ignition.gateway import IgnitionGateway
	dataDir = str(IgnitionGateway.get().getSystemManager()
				  .getDataDir().getAbsolutePath())
	path = os.path.join(dataDir, 'projects', system.util.getProjectName(),
						'com.inductiveautomation.perspective', 'views',
						'Exchange', 'Dashboard Agent', 'Dashboard', 'view.json')
	f = open(path, 'r')
	try:
		view = system.util.jsonDecode(f.read().decode('utf-8'))
	finally:
		f.close()
	for child in view['root']['children']:
		if child.get('type') == 'ia.display.dashboard':
			return child['props'].get('availableWidgets') or []
	raise ValueError('no ia.display.dashboard in %s' % path)


def plainWidgets(widgets):
	"""``props.widgets`` as a plain list, safe to hand to a popup as a param.

	Perspective popup params have to be JSON-serialisable and the live property
	object is not, so the toolbar converts before opening the Save popup.
	"""
	plain = _toPlain(widgets)
	return plain if isinstance(plain, list) else []


def _cleanName(name):
	"""Normalise a user-supplied dashboard name, or raise ValueError."""
	name = (name or u'').strip()
	if not name:
		raise ValueError('Give the dashboard a name.')
	if len(name) > MAX_NAME:
		raise ValueError('Name is too long (max %d characters).' % MAX_NAME)
	return name


def _row(rs, i):
	"""One result-set row as a plain dict, without the widgets payload."""
	return {
		'id': rs.getValueAt(i, 'id'),
		'name': rs.getValueAt(i, 'name'),
		'isDemo': bool(rs.getValueAt(i, 'is_demo')),
		'widgetCount': rs.getValueAt(i, 'widget_count'),
		'updated': system.date.format(rs.getValueAt(i, 'updated_at'),
									  'yyyy-MM-dd HH:mm'),
	}


