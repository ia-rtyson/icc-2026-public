def saveConfig(name, widgets, isDemo=None, overwrite=True):
	"""Create or update a saved dashboard.

	Saving under an existing name updates that row -- that is the "edit it and
	save" path. Saving under a new name creates a new row, which is "save as a
	new dashboard"; no separate copy operation is needed.

	Args:
		name: what to call it. Case-insensitively unique.
		widgets: the dashboard component's props.widgets (a Perspective
			property object is fine -- it is converted here).
		isDemo: True/False to set the demo flag, or None to leave an existing
			row's flag alone and default a new row to False.
		overwrite: when False, refuse to update an existing name and return
			status 'exists' instead. The Save popup passes True once the
			operator has seen the "this will update" warning.

	Returns:
		dict with status ('created' | 'updated' | 'exists' | 'error'), and on
		success the row id, name and widget count.
	"""
	_ensureTable()
	try:
		name = _cleanName(name)
	except ValueError:
		# Jython 2.7: re-derive the message rather than binding the exception,
		# so this stays valid under both 2.x comma and 'as' syntax rules.
		bad = (name or u'').strip()
		if not bad:
			return {'status': 'error', 'message': 'Give the dashboard a name.'}
		return {'status': 'error',
				'message': 'Name is too long (max %d characters).' % MAX_NAME}

	plain = _toPlain(widgets)
	if plain is None:
		plain = []
	if not isinstance(plain, list):
		return {'status': 'error',
				'message': 'Expected the widgets array, got a %s.'
						   % type(plain).__name__}

	payload = system.util.jsonEncode(plain)
	current = getConfig(name)

	if current is not None:
		if not overwrite:
			return {'status': 'exists', 'id': current['id'],
					'name': current['name']}
		# isDemo None leaves the stored flag alone -- the query COALESCEs a NULL
		demoParam = None if isDemo is None else (1 if isDemo else 0)
		system.db.runNamedQuery(PROJECT, NQ + 'UpdateConfig', {
			'id': int(current['id']),
			'name': name,
			'widgetsJson': payload,
			'isDemo': demoParam,
		})
		demo = current['isDemo'] if isDemo is None else bool(isDemo)
		log.infof('Updated dashboard "%s" (%d widgets)', name, len(plain))
		return {'status': 'updated', 'id': current['id'], 'name': name,
				'isDemo': demo, 'widgetCount': len(plain)}

	newId = system.db.runNamedQuery(PROJECT, NQ + 'InsertConfig', {
		'name': name,
		'widgetsJson': payload,
		'isDemo': 1 if isDemo else 0,
	}, getKey=True)
	log.infof('Saved dashboard "%s" (%d widgets, demo=%s)',
			  name, len(plain), bool(isDemo))
	return {'status': 'created', 'id': newId, 'name': name,
			'isDemo': bool(isDemo), 'widgetCount': len(plain)}


def isDefault(ident):
	"""True if this row id is the page's default dashboard (DEFAULT_NAME)."""
	config = getConfig(int(ident))
	return config is not None and config['name'].lower() == DEFAULT_NAME.lower()


def setDemo(ident, flag):
	"""Set or clear the demo flag -- the only column the Manage popup can edit.

	A demo dashboard survives the nightly purge; everything else does not. The
	default dashboard's flag cannot be cleared, or the purge would take it.
	"""
	_ensureTable()
	if not flag and isDefault(ident):
		return {'status': 'protected', 'isDemo': True}
	rows = system.db.runNamedQuery(PROJECT, NQ + 'UpdateConfigDemo',
								   {'id': int(ident), 'isDemo': 1 if flag else 0})
	return {'status': 'ok' if rows else 'not_found', 'isDemo': bool(flag)}


def deleteConfig(ident):
	"""Delete one saved dashboard by id. The default dashboard is refused."""
	_ensureTable()
	if isDefault(ident):
		return {'status': 'protected', 'deleted': 0}
	rows = system.db.runNamedQuery(PROJECT, NQ + 'DeleteConfig', {'id': int(ident)})
	if rows:
		log.infof('Deleted dashboard id=%s', ident)
	return {'status': 'ok' if rows else 'not_found', 'deleted': rows}


