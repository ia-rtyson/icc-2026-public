def pascal(text):
    """``query_tag_history`` / ``MODEL`` -> ``QueryTagHistory`` / ``Model``.

    Component names are PascalCase, named by purpose, with no type prefix
    (style guide); the tool tiles and model rows derive theirs from their data.
    """
    return u"".join(w[:1].upper() + w[1:].lower() for w in re.split(r"[^A-Za-z0-9]+", text) if w)


