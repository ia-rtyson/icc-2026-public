def patch_page_config(cfg):
    entry = {"title": "What is an Agent?", "viewPath": VIEW_PATH}
    if cfg["pages"].get(PAGE_PATH) == entry:
        return False
    cfg["pages"][PAGE_PATH] = entry
    return True


NAV_GROUP = {
    "icon": "person",
    "instances": [{"label": "Walkthrough", "navTo": PAGE_PATH}],
    "label": "What is an Agent?",
}


def patch_nav(nav):
    def find(node):
        if node.get("type") == "ia.display.flex-repeater":
            return node
        for child in node.get("children", []) or []:
            hit = find(child)
            if hit:
                return hit
        return None

    rep = find(nav["root"])
    if rep is None:
        raise SystemExit("gen_agent_anatomy: no flex-repeater in LeftNavigation")
    items = [i for i in rep["props"]["instances"] if i.get("label") != NAV_GROUP["label"]]
    # Top of the navigation: this is the page the talk opens on.
    new = [NAV_GROUP] + items
    if new == rep["props"]["instances"]:
        return False
    rep["props"]["instances"] = new
    return True


