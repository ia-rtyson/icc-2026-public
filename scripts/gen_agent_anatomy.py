def _cls(idx, step, kind, revealed_at):
    """The class string for one part card at a given step."""
    base = u"exchange/agent-anatomy/part exchange/agent-anatomy/%s " % kind
    return base + (u"exchange/agent-anatomy/live" if step >= revealed_at else u"exchange/agent-anatomy/idle")


def stage_class(step):
    out = [u"exchange/agent-anatomy/stage"]
    if step >= 1:
        out.append(u"exchange/agent-anatomy/on-model")
    if step >= 2:
        out.append(u"exchange/agent-anatomy/on-prompt")
    if step >= 3:
        out.append(u"exchange/agent-anatomy/on-tools")
    return u" ".join(out)


def state(step):
    """Every custom prop that depends on the step, in one place."""
    return {
        "step": step,
        "stageClass": stage_class(step),
        "promptClass": _cls(0, step, u"prompt", 2),
        "toolsClass": _cls(1, step, u"tools", 3),
        "modelClass": _cls(2, step, u"model", 1),
    }


