"""Build the "What is an AI agent?" walkthrough page.

One screen for the top of the deck: a person outline (that is the agent) and
the three parts an agent is actually made of, all shown at once --

    1. model connectivity  -- the brain
    2. the system prompt   -- what it is, and how it answers
    3. the tools           -- what it can actually do

It used to be a four-click walkthrough (Next / Back / Start over revealing one
part per click). As of 2026-09-29 it opens fully revealed with no step
controls: the cards still animate in on load and the figure's ambient
animations keep running, so it is not a static slide -- it just needs no
driving.

The worked example is a **Line Performance Report agent** for a food plant,
because that is the one every manufacturing buyer already has a person doing by
hand on a Monday morning.

Everything about the reveal is a CSS class on a custom prop:

* Each part card binds ``props.style.classes`` to a view custom prop with a
  plain **property** binding, seeded with the finished class string. No expression bindings anywhere -- an earlier feature in this project
  derived a class name in an expression and the class silently never appeared.
* The figure's wrapper carries a **cumulative** class string
  (``exchange/agent-anatomy/stage exchange/agent-anatomy/on-prompt exchange/agent-anatomy/on-tools ...``) rather than a step number, so a
  rule needs one selector rather than one per step at or above it.
* Reveal animations are keyframes with ``forwards``, not transitions, so
  seeding every card as ``exchange/agent-anatomy/live`` plays each reveal once as the page mounts.
* ``ia.shapes.svg`` emits every fill/stroke/opacity from the elements array as
  an **inline style**, not as a presentation attribute -- so a stylesheet rule
  loses to it. Only a CSS *animation* outranks an inline style, which is why
  every colour change here is a keyframe with ``forwards`` and why the opaque
  head/bust fill is declared in the elements array instead.

Perspective prefixes every SVG id per component instance, so the stylesheet
matches ``[id$="-torso"]``, never ``#torso``.

Idempotent. Rewrites the view, its stylesheet block, the page-config entry, the
left-nav group and the Home landing card each run.

Usage:  python scripts/gen_agent_anatomy.py [--check]
"""

