# ia.container.flex keeps these at the top of props, NOT inside style -- a
# `justify` or `alignItems` written into style is silently ignored. Callers pass
# them alongside the CSS keys and this lifts them out.
_FLEX_PROPS = ("justify", "alignItems", "wrap")


def flex(name, children=None, direction="column", style=None, position=None,
         props=None):
    node = {
        "meta": {"name": name},
        "type": "ia.container.flex",
        "props": {"direction": direction},
    }
    if style:
        style = dict(style)
        for key in _FLEX_PROPS:
            if key in style:
                node["props"][key] = style.pop(key)
        if style:
            node["props"]["style"] = style
    if props:
        node["props"].update(props)
    if position:
        node["position"] = position
    if children is not None:
        node["children"] = children
    return node


def label(name, text, style=None, position=None):
    node = {
        "meta": {"name": name},
        "type": "ia.display.label",
        "props": {"text": text},
    }
    if style:
        node["props"]["style"] = style
    if position:
        node["position"] = position
    return node


def bound_label(name, path, style=None, position=None):
    node = label(name, u"", style, position)
    node["propConfig"] = {
        "props.text": {"binding": {"config": {"path": path}, "type": "property"}}
    }
    return node


def icon(name, path, color, size=20, position=None):
    node = {
        "meta": {"name": name},
        "type": "ia.display.icon",
        "props": {
            "path": path,
            "color": color,
            "style": {"width": size, "height": size},
        },
    }
    if position:
        node["position"] = position
    return node




def classed(node, path, seed):
    """Bind a container's style.classes to a custom prop holding the finished
    class string. A property binding, deliberately -- see the module docstring."""
    node["props"].setdefault("style", {})["classes"] = seed
    node.setdefault("propConfig", {})["props.style.classes"] = {
        "binding": {"config": {"path": path}, "type": "property"}
    }
    return node


