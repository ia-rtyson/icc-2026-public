# --------------------------------------------------------------------------

def dump(obj):
    """Serialize the way the gateway does: Gson HTML-safe escaping, no trailing
    newline. Matching it keeps diffs scoped to real changes and stops the next
    gateway save from rewriting the whole file."""
    out = json.dumps(obj, indent=2, sort_keys=True, ensure_ascii=False)
    for ch in "<>&='":
        out = out.replace(ch, "\\u%04x" % ord(ch))
    return out


def run_script_expr(w):
    """The ``runScript`` expression that fills ``custom.payload``.

    Arg order follows each shaping function's signature: the line-shaped ones
    take a line path first, the tag-shaped ones take a tag path."""
    args = []
    kind = w["kind"]
    if kind == "line":
        args.append("{view.params.linePath}")
    elif kind == "tag":
        args.append("{view.params.tagPath}")
    elif kind == "tags":
        args.append("{view.params.tagPaths}")
    args.extend(w.get("args") or [])
    return 'runScript("exchange.dashboard.widgets.%s", %d, %s)' % (
        w["fn"], POLL_MS, ", ".join(args))


def view_params(w):
    params = {"header": "", "footer": ""}
    kind = w["kind"]
    if kind == "line":
        params["linePath"] = ""
    elif kind == "tag":
        params["tagPath"] = ""
    elif kind == "tags":
        params["tagPaths"] = ""
    params.update(w.get("params") or {})
    return params


def build_view(w):
    params = view_params(w)

    prop_config = {}
    for p in sorted(params):
        prop_config["params." + p] = {"paramDirection": "input", "persistent": True}

    # One runScript for the whole payload -- see the module docstring. PRIVATE
    # because only the chart-prop bindings read it, and they run on the
    # gateway: the chart already ships its data, the payload need not ship too.
    prop_config["custom.payload"] = {
        "access": "PRIVATE",
        "binding": {
            "config": {"expression": run_script_expr(w)},
            "type": "expr",
        }
    }

    chart_config = {}
    for prop, field in sorted(w["maps"].items()):
        path = "view.custom.payload" + ("." + field if field else "")
        chart_config[prop] = {
            "binding": {"config": {"path": path}, "type": "property"}
        }

    children = [
        {
            "meta": {"name": "Header"},
            "position": {"basis": "auto", "grow": 0, "shrink": 0},
            "propConfig": {
                "props.text": {
                    "binding": {"config": {"path": "view.params.header"},
                                "type": "property"}
                }
            },
            # Tile chrome. The dashboard component draws each widget as a
            # bare 1px near-white rectangle with no padding, which reads as a
            # wireframe rather than a card; the rest of the card look is CSS on
            # .dashboard-widget in the project stylesheet. What has to live
            # here is the inner spacing, because the tile body has no padding
            # of its own and a chart otherwise touches the border.
            "props": {"style": {"color": "var(--neutral-90)",
                                "fontSize": "12px",
                                "fontWeight": 600,
                                "letterSpacing": "0.04em",
                                "textTransform": "uppercase",
                                "whiteSpace": "nowrap",
                                "overflow": "hidden",
                                "textOverflow": "ellipsis"}},
            "type": "ia.display.label",
        },
        {
            "meta": {"name": "Chart"},
            "position": {"basis": "auto", "grow": 1},
            "propConfig": chart_config,
            "props": w.get("static_props") or {},
            "type": w["component"],
        },
        {
            "meta": {"name": "Footer"},
            "position": {"basis": "auto", "grow": 0, "shrink": 0},
            "propConfig": {
                "props.text": {
                    "binding": {"config": {"path": "view.params.footer"},
                                "type": "property"}
                }
            },
            "props": {"style": {"color": "var(--neutral-60)",
                                "fontSize": "11px",
                                "whiteSpace": "nowrap",
                                "overflow": "hidden",
                                "textOverflow": "ellipsis"}},
            "type": "ia.display.label",
        },
    ]

    cols, rows = w["size"]
    return {
        # `payload` seeds as an empty object, not null: a property binding onto
        # `view.custom.payload.series` against a null parent resolves to nothing
        # and the chart mounts with no series at all rather than an empty one.
        "custom": {"payload": {}},
        "params": params,
        "propConfig": prop_config,
        "props": {"defaultSize": {"height": 80 * rows, "width": 80 * cols}},
        "root": {
            "children": children,
            "meta": {"name": "root"},
            "props": {"direction": "column",
                      "style": {"gap": "6px", "padding": "12px 14px 10px"}},
            "type": "ia.container.flex",
        },
    }


def catalog_entry(w):
    params = view_params(w)
    view_params_block = {"_description": w["desc"] + " " + (
        LINE_PARAM_DOC if w["kind"] == "line" else "")}
    view_params_block["_generated"] = GENERATED_TAG
    for k, v in params.items():
        view_params_block[k] = v
    cols, rows = w["size"]
    return {
        "body": {"style": {"classes": ""}},
        "category": "Charts",
        "defaultSize": {"columnSpan": cols, "rowSpan": rows},
        # Dashboard chrome header off: the title comes from the view's own
        # `header` param and nowhere else. With both on, an agent that helpfully
        # sets `header` gets the title twice in every tile -- which is exactly
        # what happened the first time these were placed. This matches the
        # hand-built Line Chart widget rather than the other five.
        "header": {"enabled": False, "style": {"classes": ""}, "title": ""},
        "isConfigurable": False,
        "minSize": {"columnSpan": max(2, cols // 2), "rowSpan": max(2, rows // 2)},
        "name": w["name"],
        "style": {"classes": ""},
        "viewParams": view_params_block,
        "viewPath": "Exchange/Dashboard Agent/Dashboard Templates/" + w["key"],
    }


RESOURCE_JSON = {
    "scope": "G",
    "version": 1,
    "restricted": False,
    "overridable": True,
    "files": ["view.json"],
    "attributes": {
        "lastModification": {"actor": "external",
                             "timestamp": "2026-09-10T00:00:00Z"}
    },
}


def write(path, text, check, changed):
    existing = None
    if os.path.exists(path):
        existing = io.open(path, encoding="utf-8").read()
    if existing == text:
        return
    changed.append(os.path.relpath(path, ROOT))
    if check:
        return
    d = os.path.dirname(path)
    if not os.path.isdir(d):
        os.makedirs(d)
    io.open(path, "w", encoding="utf-8", newline="").write(text)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="report what would change, write nothing")
    args = ap.parse_args()
    changed = []

    for w in WIDGETS:
        d = os.path.join(TEMPLATE_DIR, w["key"])
        write(os.path.join(d, "view.json"), dump(build_view(w)), args.check, changed)
        write(os.path.join(d, "resource.json"), dump(RESOURCE_JSON), args.check, changed)

    # Splice the catalog: keep every entry this script does not own, append ours.
    dash = json.loads(io.open(DASHBOARD, encoding="utf-8").read())
    node = None
    for c in dash["root"]["children"]:
        if c.get("type") == "ia.display.dashboard":
            node = c
            break
    if node is None:
        sys.exit("no ia.display.dashboard in %s" % DASHBOARD)

    kept = [w for w in node["props"].get("availableWidgets") or []
            if (w.get("viewParams") or {}).get("_generated") != GENERATED_TAG]
    node["props"]["availableWidgets"] = kept + [catalog_entry(w) for w in WIDGETS]
    write(DASHBOARD, dump(dash), args.check, changed)

    if changed:
        print(("would change" if args.check else "wrote") + " %d file(s):" % len(changed))
        for c in changed:
            print("  " + c)
    else:
        print("up to date")
    print("catalog: %d hand-built + %d generated" % (len(kept), len(WIDGETS)))
    if args.check and changed:
        sys.exit(1)


if __name__ == "__main__":
    main()
