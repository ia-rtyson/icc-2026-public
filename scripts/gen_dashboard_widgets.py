#!/usr/bin/env python3
"""Generate the Dashboard Agent's canvas-chart widget templates.

Twelve template views plus their entries in the Dashboard's ``availableWidgets``
catalog. Idempotent -- rerun after editing any of the declarations below and it
rewrites every generated view and replaces its own block of catalog entries,
leaving the six hand-built widgets (line/gauge/bar/donut/radar/markdown) alone.

Why generated rather than hand-written: the twelve views differ only in which
``exchange.dashboard.widgets`` function they call and which props that function's output
feeds. Twelve near-identical view.json files diverge the moment one is touched,
and the interesting part -- the ``_description`` the agent actually reads -- gets
lost among the boilerplate.

Two things worth knowing before editing:

* **The chart family is ``ia.canvas-charts.*``**, not ``ia.echarts.*``. See
  ``shared/perspective/manifest.md``; the docs' ECharts namespace is stale for
  8.3.4 and those components do not exist on this gateway.
* **Data arrives via ``runScript`` into one custom prop, not one binding per
  prop.** Several shaping functions return ``{"data": ..., "series": ...}``
  together, and binding each prop with its own ``runScript`` call would read
  every tag twice and let the two halves land a poll apart -- a series list that
  disagrees with its data is a blank chart, not an error. So each view binds
  ``custom.payload`` once and the props read fields off it.

Usage:  python scripts/gen_dashboard_widgets.py [--check]
"""

