# --------------------------------------------------------------------------
# JSON helpers -- Perspective view.json files must keep their existing shape
# --------------------------------------------------------------------------

def read_view(path):
    """Load a view.json, remembering its formatting so we can write it back
    unchanged apart from our edit. A reformatted file is a huge, unreviewable
    diff and it will fight whatever tool wrote it originally."""
    raw = open(path, encoding="utf-8").read()
    data = json.loads(raw)

    # Indent width: first indented line of the file.
    indent = 2
    for line in raw.split("\n")[1:]:
        stripped = line.lstrip(" ")
        if stripped and stripped != line:
            indent = len(line) - len(stripped)
            break

    return data, {
        "indent": indent,
        "trailing_newline": raw.endswith("\n"),
        # Gateway-written files are key-sorted; preserve that if it holds.
        "sort_keys": raw.find('"children"') < raw.find('"type"'),
        "original": raw,
    }


def write_view(path, data, fmt, dry_run):
    out = json.dumps(
        data, indent=fmt["indent"], sort_keys=fmt["sort_keys"], ensure_ascii=False
    )
    if fmt["trailing_newline"]:
        out += "\n"
    if out == fmt["original"]:
        return False
    if not dry_run:
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(out)
    return True


def walk(node):
    """Yield (parent_list, index, node) for every component in a view tree."""
    for i, child in enumerate(node.get("children") or []):
        yield node["children"], i, child
        for item in walk(child):
            yield item


def subtree_text(node):
    return json.dumps(node)


# --------------------------------------------------------------------------
# Step 1 -- pin the AI chat component to a dark-cool palette
# --------------------------------------------------------------------------

def step_css(project_dir, dry_run, log):
    """The AI Agent module ships AiComponents.<hash>.css, which declares its own
    LIGHT palette on :root (--neutral-0: #ffffff ... --neutral-900: #121619,
    plus --accent-*, --gradient-*, --shadow-*). It never reads the Perspective
    theme, which is why the chat renders white under dark-cool.

    Every colour in that stylesheet resolves through those variables, so
    redefining the ramp is a complete fix rather than chasing ~150 rules.
    The block is SCOPED to the component (not :root) and uses a DOUBLED class
    for specificity -- see the comments inside CSS_BLOCK for why both matter."""
    path = os.path.join(
        project_dir, "com.inductiveautomation.perspective", "stylesheet", "stylesheet.css"
    )
    if not os.path.isfile(path):
        log("CSS   SKIP  no stylesheet.css at %s" % path)
        return False

    raw = open(path, encoding="utf-8").read()
    block = "%s\n%s\n%s\n" % (BEGIN, CSS_BLOCK, END)

    if BEGIN in raw:
        start = raw.index(BEGIN)
        end = raw.index(END) + len(END) + 1
        if raw[start:end] == block:
            log("CSS   OK    already applied, unchanged")
            return False
        new = raw[:start] + block + raw[end:]
        log("CSS   UPDATE refreshed existing block")
    else:
        # Insert ABOVE any generated section so we never land inside a block
        # that a generator will rewrite (e.g. wire_alarm_flood_svg.py's).
        marker = raw.find("/* >>> ")
        if marker == -1:
            new = raw.rstrip("\n") + "\n\n" + block
            log("CSS   ADD   appended block (%d lines)" % block.count("\n"))
        else:
            new = raw[:marker] + block + "\n" + raw[marker:]
            log("CSS   ADD   inserted block above generated section")

    if not dry_run:
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(new)
    return True


# --------------------------------------------------------------------------
# Step 2 -- remove the theme toggle, force the session theme
# --------------------------------------------------------------------------

def step_theme(project_dir, dry_run, log):
    """Perspective swaps themes by replacing a stylesheet link, so there is no
    class or attribute to hook theme-conditional CSS onto -- the only way to
    guarantee dark-cool is to make the theme unchangeable.

    Removes any component whose subtree writes session.props.theme, and sets
    the session default. Note this deletes the whole toggle CONTAINER, not just
    the script, so no empty affordance is left in the nav bar."""
    changed = False
    persp = os.path.join(project_dir, "com.inductiveautomation.perspective")

    # 2a. Drop every component that sets session.props.theme.
    views = os.path.join(persp, "views")
    for root, _dirs, files in os.walk(views):
        if "view.json" not in files:
            continue
        path = os.path.join(root, "view.json")
        try:
            data, fmt = read_view(path)
        except (ValueError, OSError) as exc:
            log("THEME WARN  unreadable %s (%s)" % (path, exc))
            continue
        if "session.props.theme" not in fmt["original"]:
            continue

        removed = []
        # Re-scan after each removal: deleting shifts indices.
        while True:
            hit = None
            for siblings, idx, node in walk(data.get("root", {})):
                if "session.props.theme" in subtree_text(node):
                    hit = (siblings, idx, node)
                    break
            if hit is None:
                break
            siblings, idx, node = hit
            removed.append(node.get("meta", {}).get("name", "<unnamed>"))
            del siblings[idx]

        if removed and write_view(path, data, fmt, dry_run):
            rel = os.path.relpath(path, project_dir)
            log("THEME REMOVE %s -> %s" % (rel, ", ".join(removed)))
            changed = True

    # 2b. Force the session default.
    props_path = os.path.join(persp, "session-props", "props.json")
    if os.path.isfile(props_path):
        data, fmt = read_view(props_path)
        current = data.setdefault("props", {}).get("theme")
        if current == "dark-cool":
            log("THEME OK    session default already dark-cool")
        else:
            data["props"]["theme"] = "dark-cool"
            write_view(props_path, data, fmt, dry_run)
            log("THEME SET   session default %r -> 'dark-cool'" % current)
            changed = True
    else:
        log("THEME WARN  no session-props/props.json")

    return changed


# --------------------------------------------------------------------------
# Step 3 -- make dock close buttons visible
# --------------------------------------------------------------------------

CLOSE_PROPS = {
    "text": "",
    "primary": False,
    "image": {
        "icon": {"path": "material/close", "color": "var(--neutral-90)"},
        "width": 18,
        "height": 18,
    },
    "style": {
        "backgroundColor": "transparent",
        "border": "none",
        "borderRadius": "4px",
        "cursor": "pointer",
        "minHeight": "0px",
        "minWidth": "0px",
        "padding": "0px",
    },
}


def is_close_button(node):
    if node.get("type") != "ia.input.button":
        return False
    props = node.get("props") or {}
    icon = ((props.get("image") or {}).get("icon") or {}).get("path", "")
    script = subtree_text(node.get("events") or {})
    return icon == "material/close" or "closeDock" in script


def step_close(project_dir, dry_run, log):
    """An icon-only ia.input.button is invisible by default on a dark header,
    for two compounding reasons:

      * `primary` defaults to True, so the foreground is the "on-primary"
        colour -- #121619 in dark-cool, i.e. black on a black header.
      * `text` defaults to the literal "Button", so an unset text renders that
        word (equally invisible, and it widens the control).

    It also carries a default min-height that overflows a small square and
    renders a scrollbar inside the button. This sets all three explicitly."""
    changed = False
    views = os.path.join(project_dir, "com.inductiveautomation.perspective", "views")
    for root, _dirs, files in os.walk(views):
        if "view.json" not in files:
            continue
        path = os.path.join(root, "view.json")
        try:
            data, fmt = read_view(path)
        except (ValueError, OSError):
            continue
        if "ia.input.button" not in fmt["original"]:
            continue

        fixed = []
        for _siblings, _idx, node in walk(data.get("root", {})):
            if not is_close_button(node):
                continue
            before = json.dumps(node.get("props"), sort_keys=True)
            node["props"] = json.loads(json.dumps(CLOSE_PROPS))
            node["position"] = {"basis": "28px", "shrink": 0}
            if json.dumps(node["props"], sort_keys=True) != before:
                fixed.append(node.get("meta", {}).get("name", "<unnamed>"))

        if fixed and write_view(path, data, fmt, dry_run):
            rel = os.path.relpath(path, project_dir)
            log("CLOSE FIX   %s -> %s" % (rel, ", ".join(fixed)))
            changed = True

    if not changed:
        log("CLOSE OK    no close buttons needed changes")
    return changed


# --------------------------------------------------------------------------
# Rescan
# --------------------------------------------------------------------------

def rescan(gateway_url, token, log):
    """Only project resources are touched, so /scan/projects is enough --
    a config-only change would need /scan/config as well."""
    url = gateway_url.rstrip("/") + "/data/api/v1/scan/projects"
    req = urllib.request.Request(url, data=b"", method="POST")
    req.add_header("X-Ignition-API-Token", token)
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            log("SCAN  OK    %s -> %s" % (url, resp.status))
            return True
    except urllib.error.HTTPError as exc:
        log("SCAN  FAIL  %s -> HTTP %s" % (url, exc.code))
    except Exception as exc:  # noqa: BLE001
        log("SCAN  FAIL  %s (%s)" % (url, exc))
    return False


def main():
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--project-dir", required=True,
                    help="Ignition project folder, e.g. ignition/projects/icc-2026")
    ap.add_argument("--dry-run", action="store_true", help="report without writing")
    ap.add_argument("--gateway-url", help="e.g. http://localhost:8088")
    ap.add_argument("--api-token", help="gateway API token with scan permission")
    ap.add_argument("--skip", default="", metavar="STEPS",
                    help="comma-separated steps to skip: css,theme,close")
    args = ap.parse_args()

    project_dir = os.path.abspath(args.project_dir)
    if not os.path.isdir(os.path.join(project_dir, "com.inductiveautomation.perspective")):
        sys.exit("error: %s is not an Ignition project folder "
                 "(no com.inductiveautomation.perspective/)" % project_dir)

    skip = {s.strip() for s in args.skip.split(",") if s.strip()}

    def log(msg):
        print(msg)

    print("project: %s%s\n" % (project_dir, "   [DRY RUN]" if args.dry_run else ""))

    changed = False
    if "css" not in skip:
        changed |= step_css(project_dir, args.dry_run, log)
    if "theme" not in skip:
        changed |= step_theme(project_dir, args.dry_run, log)
    if "close" not in skip:
        changed |= step_close(project_dir, args.dry_run, log)

    print()
    if args.dry_run:
        print("dry run -- nothing written.")
        return
    if not changed:
        print("no changes needed.")
        return

    if args.gateway_url and args.api_token:
        rescan(args.gateway_url, args.api_token, log)
    else:
        print("changes written. Rescan the gateway to load them:")
        print('  curl -X POST -H "X-Ignition-API-Token: $API_KEY" \\')
        print("    <gateway-url>/data/api/v1/scan/projects")


if __name__ == "__main__":
    main()
