#!/usr/bin/env bash
#
# Bake the current YouTrack instance into services/youtrack/seed/ so a brand-new
# environment comes up with the tracker already provisioned -- UI project, Stage
# field, the three-column board, the admin account, and (the whole point) the
# same permanent token that is already encrypted into the gateway's tracked MCP
# connection config.
#
# This is the "option 2" half of zero-config YouTrack: rather than minting a new
# token on first boot and having to push it into the gateway, we ship the
# instance that already has the right one. See services/youtrack/restore.sh for
# the other half.
#
# Run this only when you have deliberately changed the golden state -- added a
# board column, a custom field, a saved search. Regular demo tickets do NOT need
# a re-snapshot; the nightly purge clears them.
#
#   ./scripts/youtrack-snapshot.sh
#
# YouTrack is stopped for the duration. A live copy of an embedded database is
# not guaranteed to be consistent, and a half-written Xodus store restores as a
# corrupt instance that only fails later, on some unrelated page.

set -euo pipefail

# Git Bash on Windows rewrites anything that looks like an absolute POSIX path
# in a command line, so `-v .../seed:/out` and the `/out/...` argument after it
# both come back as C:/Program Files/Git/out/... and tar fails on a path nobody
# wrote. Measured while building this.
export MSYS_NO_PATHCONV=1

cd "$(dirname "$0")/.."

SEED_DIR="services/youtrack/seed"
SEED_FILE="$SEED_DIR/youtrack-seed.tar.gz"
PROJECT="$(grep -E '^COMPOSE_PROJECT_NAME=' .env 2>/dev/null | cut -d= -f2- || true)"
PROJECT="${PROJECT:-icc-2026}"

mkdir -p "$SEED_DIR"

echo "==> checking the state about to be baked in"
TOKEN="$(grep -E '^YOUTRACK_TOKEN=' .env 2>/dev/null | cut -d= -f2- || true)"
PORT="$(grep -E '^YOUTRACK_PORT=' .env 2>/dev/null | cut -d= -f2- || true)"
PORT="${PORT:-8089}"
if [ -n "$TOKEN" ]; then
  ISSUES=$(curl -s -H "Authorization: Bearer $TOKEN" \
    "http://localhost:${PORT}/api/issues?query=project:%20UI&fields=id&\$top=500" \
    | python -c 'import sys,json; print(len(json.load(sys.stdin)))' 2>/dev/null || echo "?")
  echo "    UI tickets currently on the board: $ISSUES"
  if [ "$ISSUES" != "0" ] && [ "$ISSUES" != "?" ]; then
    echo "    ^ these will be baked into the seed and appear on every fresh stack."
    echo "      Run exchange.issueReport.pipeline.purgeTickets(force=True) first if that is not wanted."
    printf "    continue anyway? [y/N] "
    read -r reply
    case "$reply" in [yY]*) ;; *) echo "aborted"; exit 1 ;; esac
  fi
fi

echo "==> stopping youtrack"
docker compose stop youtrack

# alpine rather than the youtrack image: it has tar, starts instantly, and does
# not run the YouTrack entrypoint against the volumes we are copying out of.
# Running as root means tar records the real uid/gid, so the restore puts the
# files back owned by YouTrack rather than by root.
echo "==> archiving data + conf"
HOSTDIR="$(pwd -W 2>/dev/null || pwd)"
docker run --rm \
  -v "${PROJECT}_youtrack-data:/src/data:ro" \
  -v "${PROJECT}_youtrack-conf:/src/conf:ro" \
  -v "${HOSTDIR}/${SEED_DIR}:/out" \
  alpine:3 \
  tar czf /out/youtrack-seed.tar.gz -C /src data conf

# `up -d`, not `start`: youtrack depends_on youtrack-init, and `start` refuses
# with "youtrack is missing dependency youtrack-init" because the one-shot is
# not running. `up -d` re-runs the init, which sees a populated volume and
# declines, then starts YouTrack.
echo "==> restarting youtrack"
docker compose up -d youtrack

# The token has to travel with the instance it belongs to. The gateway reads
# this file through the ignition service's env_file, so restoring the tracker
# and handing the gateway the matching credential happen in one step and a
# fresh environment needs no .env for the purge job to work.
if [ -n "$TOKEN" ]; then
  echo "==> writing $SEED_DIR/token.env"
  {
    echo "# The YouTrack permanent token baked into youtrack-seed.tar.gz, read by"
    echo "# the ignition service's env_file. Regenerated by scripts/youtrack-snapshot.sh"
    echo "# -- do not edit by hand, and do not let it drift from the seed beside it."
    echo "YOUTRACK_TOKEN=${TOKEN}"
  } > "$SEED_DIR/token.env"
else
  echo "==> no YOUTRACK_TOKEN in .env, skipping token.env"
  echo "    The purge job will sit at no_token on a stack restored from this seed."
fi

ls -lh "$SEED_FILE" "$SEED_DIR/token.env" 2>/dev/null || ls -lh "$SEED_FILE"
echo
echo "Seed written. Commit it:"
echo "    git add $SEED_DIR && git commit -m 'Refresh the YouTrack seed'"
echo
echo "This bakes the admin account and a permanent API token into the repo."
echo "That is the trade for a tracker that provisions itself; keep the repo"
echo "private, and treat the token as disposable -- re-mint and re-snapshot"
echo "if it ever leaves."
